const { createRequire } = require('node:module');
const { readFileSync } = require('node:fs');
const pw = createRequire(process.env.C03_PLAYWRIGHT_PACKAGE || '/home/jb/Workspace/Quevo/tests/package.json')('@playwright/test');
const { chromium, expect } = pw;
const envPath = process.env.C03_ENV_FILE || '/tmp/quevo-c03-clean/apps/api/.env';
const out = process.env.C03_EVIDENCE_DIR || '/tmp/quevo-c03-evidence';
const values = Object.fromEntries(readFileSync(envPath, 'utf8').split('\n').filter(l => l && !l.startsWith('#')).map(l => [l.slice(0,l.indexOf('=')), l.slice(l.indexOf('=')+1)]));
(async () => {
  const browser = await chromium.launch({ headless: true });
  console.log('Chromium: ' + browser.version());
  const context = await browser.newContext({ baseURL: 'http://localhost:3000', viewport: {width:1280,height:900} });
  try {
    const page = await context.newPage();
    await page.goto('/login');
    await page.waitForLoadState('networkidle');
    await page.getByLabel('Email').fill('customer@quevo.local');
    await page.getByLabel('Password').fill(values.QUEVO_CUSTOMER_PASSWORD);
    await page.getByRole('button', {name:'Sign in'}).click();
    await expect(page.getByText('Signed in as Demo Customer')).toBeVisible();
    console.log('PASS: customer sign-in through web server and real API');
    await page.goto('/customer');
    await page.getByRole('button', {name:'General Service at Quevo Demo Branch'}).click();
    await page.getByRole('button', {name:'Join queue'}).click();
    await expect(page.getByTestId('ticket-number')).toHaveText('1');
    await expect(page.getByRole('status')).toHaveText('WAITING');
    await page.reload();
    await expect(page.getByTestId('ticket-number')).toHaveText('1');
    await expect(page.getByRole('status')).toHaveText('WAITING');
    await page.screenshot({path:out+'/customer-ticket.png',fullPage:true});
    console.log('PASS: ticket 1 created in PostgreSQL and recovered after reload; screenshot customer-ticket.png');
    const opContext = await browser.newContext({baseURL:'http://localhost:3000',viewport:{width:1280,height:900}});
    const operator = await opContext.newPage();
    await operator.goto('/login');
    await operator.waitForLoadState('networkidle');
    await operator.getByLabel('Email').fill('operator@quevo.local');
    await operator.getByLabel('Password').fill(values.QUEVO_OPERATOR_PASSWORD);
    await operator.getByRole('button', {name:'Sign in'}).click();
    await expect(operator.getByText('Signed in as Demo Operator')).toBeVisible();
    await operator.getByRole('link', {name:'Open operator queue'}).click();
    await expect(operator.getByText('Ticket 1',{exact:true})).toBeVisible();
    await operator.getByRole('button', {name:'Call next'}).click();
    await expect(operator.getByTestId('operator-current-ticket')).toHaveText('1');
    await operator.getByRole('button', {name:'Start service'}).click();
    await expect(operator.getByText('In service',{exact:true})).toBeVisible();
    await operator.getByRole('button', {name:'Complete service'}).click();
    await expect(operator.getByText('Service completed.')).toBeVisible();
    await operator.screenshot({path:out+'/operator-completed.png',fullPage:true});
    console.log('PASS: operator sign-in, call, start and complete ticket; screenshot operator-completed.png');
    await page.reload();
    await expect(page.getByRole('status')).toHaveText('COMPLETED');
    console.log('PASS: customer reload observes committed COMPLETED status');
  } finally { await browser.close(); }
})().catch(e => { console.error(e.message); process.exitCode=1; });
